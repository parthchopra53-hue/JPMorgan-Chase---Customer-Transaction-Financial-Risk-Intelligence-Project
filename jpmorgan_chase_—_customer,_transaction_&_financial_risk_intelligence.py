# Monthly customer behavior

monthly_behavior = (
    transactions
    .groupby([
        "customer_id",
        transactions["transaction_date"].dt.to_period("M")
    ])
    .agg(
        transaction_volume=("transaction_id", "count"),
        total_amount=("amount", "sum"),
        average_amount=("amount", "mean")
    )
    .reset_index()
)

monthly_behavior["month"] = (
    monthly_behavior["transaction_date"]
    .dt.to_timestamp()
)

monthly_behavior.head()

#Customer's historical baseline

monthly_behavior = monthly_behavior.sort_values(
    ["customer_id", "month"]
)

monthly_behavior["volume_baseline"] = (
    monthly_behavior
    .groupby("customer_id")["transaction_volume"]
    .transform(
        lambda x: x.shift(1).rolling(3, min_periods=2).mean()
    )
)

monthly_behavior["amount_baseline"] = (
    monthly_behavior
    .groupby("customer_id")["total_amount"]
    .transform(
        lambda x: x.shift(1).rolling(3, min_periods=2).mean()
    )
)

#Behavioral drift

monthly_behavior["volume_change_pct"] = (
    (
        monthly_behavior["transaction_volume"]
        - monthly_behavior["volume_baseline"]
    )
    / monthly_behavior["volume_baseline"]
) * 100

monthly_behavior["amount_change_pct"] = (
    (
        monthly_behavior["total_amount"]
        - monthly_behavior["amount_baseline"]
    )
    / monthly_behavior["amount_baseline"]
) * 100

